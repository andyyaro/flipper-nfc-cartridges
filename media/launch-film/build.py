"""Write the scene and 3D-shot windows into index.html, the burned-in subtitles into compositions/subs.html and the
whole narration as captions into renders/flipper-nfc-cartridges-v1.en.vtt.

    python3 -I build.py
    node scripts/build-icons.mjs .      # the HIG Native glyph sprite (only when the icon list changes)

Each scene host's data-start/data-duration and the root duration come from the same numbers the scenes read at
runtime (window.TM in assets/timing.js, sound/timing.json), so the two can never drift apart. The subtitle cues are
cut from the narration's own word times (narration/words.json -> assets/vo.js): a re-voiced or re-slotted line
re-times its subtitles here, and the scenes re-time themselves through the W() helper.
"""
import html, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TM = json.loads((ROOT / "sound/timing.json").read_text())
vo_js = (ROOT / "assets/vo.js").read_text()
VO = json.loads(vo_js[vo_js.index("{"): vo_js.rindex("}") + 1])
HOSTS = {"s1-hook": "s1", "s2-title": "s2", "s3-burn": "s3", "s4-board": "s4", "s5-play": "s5", "s6-proof": "s6",
         "s7-end": "s7"}
r = lambda x: f"{x:.3f}".rstrip("0").rstrip(".")

# Subtitle cues (compositions/subs.html, one layer over the scenes): at most 2 lines of 42 characters. The title (v03)
# and the end card (v12) are on screen in big type and are not subtitled. Each chunk must be the next words of its line.
SUBS = [
    ("v01", "A plain NFC sticker holds 504 bytes."),
    ("v02", "That's room for a whole song."),
    ("v04", "Pick a song, then hold\na blank sticker to the back."),
    ("v05", "It burns the tune on, page by page,\nin under two seconds."),
    ("v06", "Ode to Joy takes 100 bytes."),
    ("v07", "Nothing goes on the SD card."),
    ("v07", "The song is a standard NDEF text record,\nso phones can read it too."),
    ("v08", "It writes the length last, so a torn burn\nreads as blank, never half a song."),
    ("v09", "Then it reads the sticker back\nand checks every byte."),
    ("v10", "Tap it in Play, and the Flipper plays it\nstraight off the sticker."),
    ("v11", "It burns NTAG213, 215 and 216 stickers,\nfrom a short jingle to 250 notes."),
]
LEAD, TAIL, GAP = 0.08, 0.30, 0.04
ON_SCREEN = [("v03", "NFC Cartridges, for Flipper Zero."), ("v12", "NFC Cartridges.\nSongs that live on a sticker.")]
VTT = sorted(SUBS + ON_SCREEN, key=lambda c: int(c[0][1:]))


def cues(items=SUBS):
    pos, out = {}, []
    for k, text in items:
        n = len(text.split())
        words = VO[k]["words"][pos.get(k, 0): pos.get(k, 0) + n]
        got = " ".join(w["w"] for w in words)
        assert got == " ".join(text.split()), f"{k}: subtitle words {text!r} do not match the narration {got!r}"
        for line in text.split("\n"):
            assert len(line) <= 42, f"{k}: subtitle line over 42 characters: {line!r}"
        pos[k] = pos.get(k, 0) + n
        out.append([words[0]["t0"] - LEAD, words[-1]["t1"] + TAIL, text])
    for a, b in zip(out, out[1:]):
        a[1] = min(a[1], b[0] - GAP)
    return out


if not (ROOT / "index.html").exists():
    raise SystemExit("build.py: no index.html yet")
s = (ROOT / "index.html").read_text()
for host, key in HOSTS.items():
    a, b = TM[key]
    s, n = re.subn(rf'(<div id="{host}"[^>]*?data-start=")[^"]*(" data-duration=")[^"]*(")', rf"\g<1>{r(a)}\g<2>{r(b - a)}\g<3>", s)
    assert n == 1, host
s, n = re.subn(r'(<div id="main"[^>]*?data-duration=")[^"]*(")', rf"\g<1>{r(TM['duration'])}\g<2>", s); assert n == 1
s, n = re.subn(r'(<audio id="soundtrack"[^>]*?data-duration=")[^"]*(")', rf"\g<1>{r(TM['duration'])}\g<2>", s); assert n == 1
s, n = re.subn(r'(<div id="subtitles"[^>]*?data-duration=")[^"]*(")', rf"\g<1>{r(TM['duration'])}\g<2>", s); assert n == 1
# the 3D shots: each clip starts on the film frame stage/render.py began it on (assets/stage/<shot>.json)
for shot in TM["shots3d"]:
    j = json.loads((ROOT / f"assets/stage/{shot}.json").read_text())
    s, n = re.subn(rf'(<video id="v-{shot}"[^>]*?data-start=")[^"]*(" data-duration=")[^"]*(")',
                   rf"\g<1>{r(j['start'])}\g<2>{r(j['frames'] / j['fps'])}\g<3>", s)
    assert n == 1, shot
(ROOT / "index.html").write_text(s)

C = cues()
subs = ROOT / "compositions/subs.html"
block = "<!-- HF:SUBS (generated by build.py from window.VO, do not hand-edit) -->\n" + "".join(
    f'    <div id="sub-{i}" class="sub" data-t0="{r(a)}" data-t1="{r(b)}">{html.escape(t, quote=False).replace("'", "’")}</div>\n'
    for i, (a, b, t) in enumerate(C, 1)) + "    <!-- /HF:SUBS -->"
t, n = re.subn(r"<!-- HF:SUBS[\s\S]*?<!-- /HF:SUBS -->", lambda m: block, subs.read_text()); assert n == 1
subs.write_text(t)
def ts(x):
    ms = int(round(max(0.0, x) * 1000))
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d}.{ms % 1000:03d}"


V = cues(VTT)
(ROOT / "renders").mkdir(exist_ok=True)
(ROOT / "renders/flipper-nfc-cartridges-v1.en.vtt").write_text("WEBVTT\n\n" + "".join(
    f"{i}\n{ts(a)} --> {ts(b)}\n{t}\n\n" for i, (a, b, t) in enumerate(V, 1)))
print("index.html:", ", ".join(f"{k} {TM[k][0]}-{TM[k][1]}" for k in HOSTS.values()), f"| {TM['duration']} s | subs.html: {len(C)} cues | renders/flipper-nfc-cartridges-v1.en.vtt: {len(V)} cues")
